const mergedLocaleDictionaries: Record<LocaleCode, MessageDictionary> = {
  'zh-CN': {
    ...localeDictionaries['zh-CN'],
    ...localePatches['zh-CN'],
  },
  'en-US': {
    ...localeDictionaries['en-US'],
    ...localePatches['en-US'],
  },
};

function normalizeLocale(value: string | null | undefined): LocaleCode | null {
  if (!value) return null;

  const normalized = value.toLowerCase();

  if (normalized.startsWith('zh')) {
    return 'zh-CN';
  }

  if (normalized.startsWith('en')) {
    return 'en-US';
  }

  if (value === 'zh-CN' || value === 'en-US') {
    return value;
  }

  return null;
}

function detectSystemLocale(): LocaleCode {
  const candidates = [
    process.env.AG_LANG,
    process.env.AGILEBUILDER_LOCALE,
    process.env.LC_ALL,
    process.env.LC_MESSAGES,
    process.env.LANG,
    Intl.DateTimeFormat().resolvedOptions().locale,
  ];

  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) {
      return locale;
    }
  }

  return 'zh-CN';
}

export function getEffectiveLocale(preferredLocale?: 'auto' | LocaleCode | null): LocaleCode {
  if (preferredLocale && preferredLocale !== 'auto') {
    return preferredLocale;
  }

  return detectSystemLocale();
}

let currentLocale: LocaleCode = getEffectiveLocale(normalizeLocale(process.env.AGILEBUILDER_LOCALE) ?? 'auto');

export function setLocale(locale: LocaleCode): void {
  currentLocale = locale;
}

export function getLocale(): LocaleCode {
  return currentLocale;
}

export function t(key: string, params?: Record<string, unknown>): string {
  const dictionary = mergedLocaleDictionaries[currentLocale] || mergedLocaleDictionaries['zh-CN'];
  const fallbackDictionary = mergedLocaleDictionaries['zh-CN'];
  const value = dictionary[key] ?? fallbackDictionary[key] ?? key;
  if (typeof value === 'function') {
    return value(params ?? {});
  }
  return value;
}
